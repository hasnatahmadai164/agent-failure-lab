from collections.abc import Callable

import pytest

from agent_failure_lab.catalog import (
    END_MARKER,
    START_MARKER,
    catalog_page,
    catalog_table,
    splice,
)
from agent_failure_lab.errors import CatalogError
from agent_failure_lab.scenario import ScenarioDefinition

MakeScenario = Callable[..., ScenarioDefinition]


def test_the_table_has_a_header_and_a_row_for_each_failure(make_scenario: MakeScenario) -> None:
    scenarios = [make_scenario("first-one"), make_scenario("second-one")]

    lines = catalog_table(scenarios).splitlines()

    assert lines[0] == "| Failure | Category | What goes wrong | Fix |"
    assert len(lines) == 4


def test_each_row_links_to_the_failures_own_readme(make_scenario: MakeScenario) -> None:
    table = catalog_table([make_scenario("duplicate-side-effect")])

    assert "(src/agent_failure_lab/failures/duplicate_side_effect/README.md)" in table


def test_the_link_prefix_moves_the_links_for_a_page_in_a_subfolder(
    make_scenario: MakeScenario,
) -> None:
    table = catalog_table([make_scenario("duplicate-side-effect")], prefix="../")

    assert "(../src/agent_failure_lab/failures/duplicate_side_effect/README.md)" in table


def test_a_pipe_in_a_summary_does_not_split_the_cell(make_scenario: MakeScenario) -> None:
    table = catalog_table([make_scenario(summary="a | b")])

    assert "a \\| b" in table


def test_the_page_lists_guards_and_whether_a_failure_can_run_live(
    make_scenario: MakeScenario,
) -> None:
    page = catalog_page(
        [
            make_scenario("live-one", guards=("IdempotencyKeys", "IdempotencyStore"), live=True),
            make_scenario("plain-one"),
        ]
    )

    assert "`IdempotencyKeys`, `IdempotencyStore`" in page
    rows = [line for line in page.splitlines() if line.startswith("| [")]
    assert rows[0].endswith("| yes |")
    assert rows[1].endswith("| no |")
    assert "generated by `scripts/generate_catalog.py`" in page


def test_splice_replaces_only_what_is_between_the_markers() -> None:
    text = f"before\n{START_MARKER}\nold table\n{END_MARKER}\nafter\n"

    assert splice(text, "new table") == f"before\n{START_MARKER}\nnew table\n{END_MARKER}\nafter\n"


def test_splicing_twice_gives_the_same_text() -> None:
    text = f"top\n{START_MARKER}\n{END_MARKER}\nbottom\n"

    once = splice(text, "table")

    assert splice(once, "table") == once


@pytest.mark.parametrize(
    "text",
    [
        "no markers at all",
        f"{START_MARKER} only the start",
        f"{END_MARKER} before {START_MARKER}",
    ],
)
def test_splice_refuses_a_document_without_a_proper_pair_of_markers(text: str) -> None:
    with pytest.raises(CatalogError, match="catalog:start"):
        splice(text, "table")
