from collections.abc import Sequence

from agent_failure_lab.errors import CatalogError
from agent_failure_lab.registry import module_name
from agent_failure_lab.scenario import Scenario

START_MARKER = "<!-- catalog:start -->"
END_MARKER = "<!-- catalog:end -->"
FAILURES_DIR = "src/agent_failure_lab/failures/"


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _link(scenario: Scenario, prefix: str) -> str:
    return f"[`{scenario.slug}`]({prefix}{FAILURES_DIR}{module_name(scenario.slug)}/README.md)"


def catalog_table(scenarios: Sequence[Scenario], *, prefix: str = "") -> str:
    """The table in the README: failure, category, what goes wrong, and the fix."""
    lines = [
        "| Failure | Category | What goes wrong | Fix |",
        "| --- | --- | --- | --- |",
    ]
    for scenario in scenarios:
        row = (_link(scenario, prefix), scenario.category, scenario.summary, scenario.fix)
        lines.append("| " + " | ".join(_cell(part) for part in row) + " |")
    return "\n".join(lines)


def catalog_page(scenarios: Sequence[Scenario]) -> str:
    """The full catalogue page, with the guards each fix uses and whether it can run live."""
    lines = [
        "# Catalog",
        "",
        "Every failure in the library. This page is generated by `scripts/generate_catalog.py`,",
        "so edit the failure itself and run the script instead of changing this file by hand.",
        "",
        "| Failure | Category | What goes wrong | Fix | Guards | Live |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for scenario in scenarios:
        guards = ", ".join(f"`{name}`" for name in scenario.guards)
        row = (
            _link(scenario, "../"),
            scenario.category,
            scenario.summary,
            scenario.fix,
            guards,
            "yes" if scenario.supports_live else "no",
        )
        lines.append("| " + " | ".join(_cell(part) for part in row) + " |")
    return "\n".join(lines) + "\n"


def splice(text: str, body: str) -> str:
    """Replace what sits between the catalogue markers, leaving the rest of the text alone."""
    start = text.find(START_MARKER)
    end = text.find(END_MARKER)
    if start == -1 or end == -1 or end < start:
        raise CatalogError(f"Could not find {START_MARKER} and {END_MARKER} in the document")
    head = text[: start + len(START_MARKER)]
    return f"{head}\n{body}\n{text[end:]}"
